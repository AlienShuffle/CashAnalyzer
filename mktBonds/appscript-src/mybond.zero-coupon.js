/**
 * Given a set of TIPS with current marketable clean prices, creates a
 * Svensson real zero-coupon curve fit and analyzes each security against
 * the fitted curve.
 *
 * Produces model clean prices, price residuals, market/model YTMs, and
 * yield-equivalent residuals in basis points.
 *
 * Input ranges may be Google Sheets column/row ranges. They are flattened
 * internally before processing.
 *
 * @param {Date} settle Settlement date
 * @param {Date[]} maturities Array/range of TIPS maturity dates
 * @param {number[]} coupons Array/range of matching annual coupons, decimal
 * @param {number[]} prices Array/range of matching quoted real clean prices
 *
 * @return {Array[]} 2D analysis table suitable for display in Sheets
 * @customfunction
 */
function mybondsZeroAnalyze(settle, maturities, coupons, prices, forward = null) {

  const settleDate = mydateNormalize_(settle);

  // Sheets normally supplies ranges as two-dimensional arrays such as
  // [[value1], [value2], ...]. Normalize them to simple one-dimensional arrays.
  maturities = maturities.flat();
  coupons = coupons.flat();
  prices = prices.flat();

  // Validate matching input dimensions.
  if (maturities.length !== coupons.length) {
    throw new Error(
      `maturities.length:${maturities.length} != coupons.length:${coupons.length}`
    );
  }

  if (maturities.length !== prices.length) {
    throw new Error(
      `maturities.length:${maturities.length} != prices.length:${prices.length}`
    );
  }

  if (maturities.length === 0) {
    throw new Error("No TIPS supplied");
  }

  // Build the bond objects expected by the Svensson fitter.
  const bonds = [];
  for (let i = 0; i < maturities.length; i++) {

    const maturity = mydateNormalize_(maturities[i]);
    const coupon = Number(coupons[i]);
    const cleanPrice = Number(prices[i]);

    if (!Number.isFinite(coupon)) {
      throw new Error(
        `Invalid coupon at input row ${i + 1}: ${coupons[i]}`
      );
    }

    if (!Number.isFinite(cleanPrice) || cleanPrice <= 0) {
      throw new Error(
        `Invalid clean price at input row ${i + 1}: ${prices[i]}`
      );
    }

    bonds.push({
      maturity: maturity,
      coupon: coupon,
      cleanPrice: cleanPrice
    });
  }

  // ------------------------------------------------------------
  // Fit the real Svensson zero-coupon curve.
  // ------------------------------------------------------------

  const fit = fitTipsSvensson_(settleDate, bonds);
  const params = fit.params;

  Logger.log(`params=${params}`);
  Logger.log(`objective=${fit.objective}`);

  // ------------------------------------------------------------
  // Sample fitted zero rates for diagnostic purposes.
  // These are continuously compounded real zero rates.
  // ------------------------------------------------------------
  /*
    const z5 = svenssonZero(5, params);
    const z10 = svenssonZero(10, params);
    const z20 = svenssonZero(20, params);
  
    Logger.log(
      `zero rates: 5Y=${z5}, 10Y=${z10}, 20Y=${z20}`
    );
  */

  // ------------------------------------------------------------
  // Create the 2D output table.
  // ------------------------------------------------------------
  const result = [[
    "Maturity",
    "Coupon",
    "Market Clean",
    "Model Clean",
    "Price Residual",
    "Market YTM",
    "Model YTM",
    "Residual (bp)"
  ]];

  // ------------------------------------------------------------
  // Analyze each TIPS against the fitted zero curve.
  // ------------------------------------------------------------

  for (const bond of bonds) {

    // Model dirty price from individually discounted real cash flows.
    const modelDirty =
      mytipsZeroModelPrice(
        settleDate,
        bond.maturity,
        bond.coupon,
        params
      );


    // Convert model dirty price to model clean price.
    const accrued =
      mybondAccruedInterest(
        settleDate,
        bond.maturity,
        bond.coupon
      );

    const modelClean = modelDirty - accrued;

    // Market minus model price.
    //
    // Negative:
    //   market price < model price
    //   bond is cheap to fitted zero curve
    //
    // Positive:
    //   market price > model price
    //   bond is rich to fitted zero curve
    //
    const priceResidual = bond.cleanPrice - modelClean;


    // Obtain conventional YTM for both the actual market price and
    // the synthetic price generated by the zero curve.
    const marketYtm =
      myYieldFromPrice(
        settleDate,
        bond.maturity,
        bond.coupon,
        bond.cleanPrice
      );

    const modelYtm =
      myYieldFromPrice(
        settleDate,
        bond.maturity,
        bond.coupon,
        modelClean
      );

    // Express the zero-curve price discrepancy as an equivalent
    // conventional YTM difference.
    //
    // Positive:
    //   market YTM > model YTM
    //   bond is cheap to fitted zero curve
    //
    // Negative:
    //   market YTM < model YTM
    //   bond is rich to fitted zero curve
    //
    const residualBp = (marketYtm - modelYtm) * 10000;

    // Add one row to the Sheets output table.
    result.push([
      bond.maturity,
      bond.coupon,
      bond.cleanPrice,
      mybondRoundPrice(modelClean),
      mybondRoundPrice(priceResidual),
      marketYtm,
      modelYtm,
      residualBp
    ]);
  }
  // ------------------------------------------------------------
  // Sample fitted zero rates for diagnostic purposes.
  // These are continuously compounded real zero rates.
  // ------------------------------------------------------------

  if (forward !== null && forward !== '') {
    result.push(['---']);
    const forwardDate = mydateNormalize_(forward);
    const fwdYrs = mydateDaysBetween_(settleDate, forwardDate) / mydateDaysInYearFrom_(settleDate);
    const zFwd = svenssonZero(fwdYrs, params);
    result.push([
      forwardDate,
      ,
      ,
      ,
      ,
      ,
      mybondRoundYield(zFwd),
    ]);

    result.push(['---']);
    years = [1, 2, 5, 7, 10, 20, 30];
    const today = new Date;
    for (let i = 0; i < years.length; i++) {
      const date = new Date(today.getFullYear() + years[i], today.getMonth(), today.getDate());
      result.push([
        date,
        ,
        ,
        ,
        ,
        ,
        mybondRoundYield(svenssonZero(years[i], params)),
      ]);
    }
    result.push(['--- NSS params']);
    result.push(params);
    result.push(['--- NSS Objective']);
    result.push(fit.objective);
  }
  // ------------------------------------------------------------
  // Return rectangular 2D array for Sheets.
  // ------------------------------------------------------------
  return result;
}

// find the difference between the bond and the model's dirty prices
function mytipsZeroResidual_(
  settle,
  bond,
  params
) {

  const accrued =
    mybondAccruedInterest(
      settle,
      bond.maturity,
      bond.coupon
    );

  const marketDirty =
    bond.cleanPrice + accrued;

  const modelDirty =
    mytipsZeroModelPrice(
      settle,
      bond.maturity,
      bond.coupon,
      params
    );

  return modelDirty - marketDirty;
}
/**
 * Svensson continuously compounded zero yield.
 * Input range p may be Google Sheets column/row range. It is flattened
 * internally before processing.
 *
 * @param {Date} settle Settlement date
 * @param {Date} maturity TIPS maturity date
 * @param {number} coupon decimal
 * @param {number[]} params [beta0,beta1,beta2,beta3,tau1,tau2]
 * @customfunction
 */
function mytipsZeroModelPrice(
  settle,
  maturity,
  coupon,
  params
) {

  const settleDate = mydateNormalize_(settle);

  const maturityDate = mydateNormalize_(maturity);
  const schedule = mybondCouponSchedule(settleDate, maturityDate);

  if (schedule.length === 0)
    return null;

  let dirtyPV = 0;

  for (let i = 0;
    i < schedule.length;
    i++) {

    const paymentDate =
      schedule[i];

    const t =
      mydateDaysBetween_(
        settleDate,
        paymentDate
      ) / 365;

    const couponCF =
      100 * coupon / 2;

    const principal =
      (i === schedule.length - 1)
        ? 100
        : 0;

    const cf =
      couponCF + principal;

    dirtyPV +=
      cf * svenssonDF_(t, params);
  }

  return dirtyPV;
}

/**
 * Svensson discount factor
 * @param {number} t years (term)
 * @param {[]} p svensson parameter set
 * @returns number discount factor
*/
function svenssonDF_(t, p) {

  const z = svenssonZero(t, p);
  return Math.exp(-z * t);
}

/**
 * Svensson continuously compounded zero yield.
 * Input range p may be Google Sheets column/row range. It is flattened
 * internally before processing.
 *
 * @param {number} t years
 * @param {number[]} p [beta0,beta1,beta2,beta3,tau1,tau2]
 * @return {number} continuously compounded zero yield, decimal
 * @customfunction
 */
function svenssonZero(t, p) {

  const [b0, b1, b2, b3, tau1, tau2] = p.flat() ;

  if (t <= 0)
    return b0 + b1;

  const x1 = t / tau1;
  const x2 = t / tau2;

  const a1 =
    (1 - Math.exp(-x1)) / x1;

  const a2 =
    a1 - Math.exp(-x1);

  const a3 =
    (1 - Math.exp(-x2)) / x2
    - Math.exp(-x2);

  return b0 +
    b1 * a1 +
    b2 * a2 +
    b3 * a3;
}

/**
 * Optimized Svensson zero-curve fitter.
 *
 * Fits continuously compounded zero rates to observed bond dirty prices.
 *
 * Input bonds:
 * [
 *   {
 *     maturity: Date,
 *     coupon: decimal annual coupon,
 *     cleanPrice: quoted clean price
 *   },
 *   ...
 * ]
 *
 * Returns:
 * {
 *   params: [beta0, beta1, beta2, beta3, tau1, tau2],
 *   objective: weighted SSE
 * }
 *
 * Compatible with svenssonZero_(t, params).
 */
function fitTipsSvensson_(settle, bonds) {

  const settleDate = mydateNormalize_(settle);

  if (!Array.isArray(bonds) || bonds.length < 6) {
    throw new Error(
      `Svensson fit requires at least 6 bonds; found ${bonds.length}`
    );
  }

  // ============================================================
  // 1. PRECOMPUTE EVERYTHING THAT DOES NOT CHANGE DURING FITTING
  // ============================================================

  const prepared = [];

  for (const bond of bonds) {

    const maturityDate =
      mydateNormalize_(bond.maturity);

    const coupon =
      Number(bond.coupon);

    const cleanPrice =
      Number(bond.cleanPrice);

    if (!Number.isFinite(coupon) ||
      !Number.isFinite(cleanPrice) ||
      cleanPrice <= 0)
      continue;

    if (!mydateLessThan_(settleDate, maturityDate))
      continue;


    // Generate schedule ONCE.
    const schedule =
      mybondCouponSchedule(
        settleDate,
        maturityDate
      );

    if (!schedule ||
      schedule.length === 0)
      continue;


    // Accrued interest ONCE.
    const accrued =
      mybondAccruedInterest(
        settleDate,
        maturityDate,
        coupon,
        schedule
      );

    const marketDirty =
      cleanPrice + accrued;


    // Precalculate times and cash flows.
    const times = new Array(schedule.length);
    const cashFlows = new Array(schedule.length);

    for (let i = 0; i < schedule.length; i++) {

      const t =
        mydateDaysBetween_(
          settleDate,
          schedule[i]
        ) / 365;

      times[i] = t;

      cashFlows[i] =
        100 *
        (
          coupon / 2 +
          (i === schedule.length - 1 ? 1 : 0)
        );
    }


    // duration used only for weighting.
    //
    // Using maturity here avoids calculating full modified duration
    // inside the fitting loop.
    // Calculate the observed market YTM once.
    // Used only to determine duration weighting.
    const marketYld =
      myYieldFromPrice(
        settleDate,
        maturityDate,
        coupon,
        cleanPrice
      );

    if (!Number.isFinite(marketYld))
      continue;

    // Calculate duration once, outside the optimizer.
    const duration =
      calculateDuration(
        settleDate,
        maturityDate,
        coupon,
        marketYld
      );

    if (!Number.isFinite(duration) || duration <= 0)
      continue;

    // GSW objective uses inverse-duration weighting.
    const weight =
      1 / duration;


    prepared.push({
      marketDirty: marketDirty,
      times: times,
      cashFlows: cashFlows,
      weight: weight
    });
  }


  if (prepared.length < 6) {
    throw new Error(
      `Insufficient usable bonds for Svensson fit: ${prepared.length}`
    );
  }

  // ============================================================
  // 2. FAST SVENSSON ZERO FUNCTION
  //
  // This deliberately avoids:
  //
  //   array destructuring
  //   helper-function calls
  //   temporary arrays
  //
  // because this code runs thousands/millions of times.
  // ============================================================

  function zero_(
    t,
    b0,
    b1,
    b2,
    b3,
    tau1,
    tau2
  ) {

    if (t <= 0) return b0 + b1;

    const x1 = t / tau1;
    const e1 = Math.exp(-x1);

    const a1 = (1 - e1) / x1;

    const a2 = a1 - e1;

    const x2 = t / tau2;
    const e2 = Math.exp(-x2);

    const a3 = (1 - e2) / x2 - e2;

    return (
      b0 +
      b1 * a1 +
      b2 * a2 +
      b3 * a3
    );
  }

  // ============================================================
  // 3. FAST OBJECTIVE FUNCTION
  // ============================================================

  function objective_(p) {

    const b0 = p[0];
    const b1 = p[1];
    const b2 = p[2];
    const b3 = p[3];
    const tau1 = p[4];
    const tau2 = p[5];

    // Reject invalid decay constants immediately.
    if (tau1 <= 0.05 ||
      tau2 <= 0.05)
      return Number.POSITIVE_INFINITY;


    let sse = 0;


    for (let j = 0; j < prepared.length; j++) {

      const bond = prepared[j];
      const times = bond.times;
      const cashFlows = bond.cashFlows;
      let pv = 0;
      for (let i = 0; i < times.length; i++) {

        const t = times[i];

        const z =
          zero_(
            t,
            b0,
            b1,
            b2,
            b3,
            tau1,
            tau2
          );

        const df = Math.exp(-z * t);

        pv += cashFlows[i] * df;
      }

      const error = pv - bond.marketDirty;

      // Duration-style weighting.
      sse +=
        bond.weight *
        error *
        error;
    }

    return sse;
  }


  // ============================================================
  // 4. REASONABLE STARTING PARAMETERS
  //
  // Betas are decimal yields.
  // ============================================================

  let p = [
    0.0200,   // beta0
    -0.0050,  // beta1
    0.0050,   // beta2
    0.0000,   // beta3
    1.50,     // tau1
    6.00      // tau2
  ];


  // ============================================================
  // 5. COARSE PARAMETER SEARCH
  //
  // Much smaller than the previous 500-iteration six-dimensional
  // coordinate descent.
  // ============================================================

  const tau1Grid = [
    0.50,
    1.00,
    1.50,
    2.00,
    3.00
  ];

  const tau2Grid = [
    3.00,
    4.00,
    5.00,
    7.00,
    10.00,
    15.00,
    20.00,
    30.00
  ];


  let best =
    Number.POSITIVE_INFINITY;

  let bestP =
    p.slice();


  // ============================================================
  // For each tau pair, do a relatively cheap beta optimization.
  // ============================================================

  for (let t1i = 0; t1i < tau1Grid.length; t1i++) {

    for (let t2i = 0; t2i < tau2Grid.length; t2i++) {

      const tau1 = tau1Grid[t1i];
      const tau2 = tau2Grid[t2i];
      // Skip nearly identical decay constants.
      if (Math.abs(tau1 - tau2) < 0.10) continue;

      let candidate = [
        p[0],
        p[1],
        p[2],
        p[3],
        tau1,
        tau2
      ];

      let candidateValue =
        objective_(candidate);


      // Beta-only coordinate descent.
      //
      // These start at 25 bp and progressively shrink.
      const betaSteps = [
        0.0025,
        0.0025,
        0.0025,
        0.0025
      ];


      for (let iteration = 0; iteration < 60; iteration++) {

        let improved = false;

        for (let j = 0; j < 4; j++) {

          const original = candidate[j];


          // Try downward.
          candidate[j] = original - betaSteps[j];

          let value = objective_(candidate);

          if (value < candidateValue) {

            candidateValue = value;
            improved = true;
            continue;
          }


          // Try upward.
          candidate[j] = original + betaSteps[j];

          value = objective_(candidate);

          if (value < candidateValue) {

            candidateValue = value;
            improved = true;
            continue;
          }

          // Neither direction helped.
          candidate[j] = original;
        }

        if (!improved) {

          let maxStep = 0;

          for (let j = 0;
            j < 4;
            j++) {

            betaSteps[j] *= 0.5;

            maxStep =
              Math.max(
                maxStep,
                betaSteps[j]
              );
          }


          if (maxStep < 1e-7)
            break;
        }
      }


      if (candidateValue < best) {

        best =
          candidateValue;

        bestP =
          candidate.slice();
      }
    }
  }

  // ============================================================
  // 6. LOCAL SIX-PARAMETER REFINEMENT
  //
  // We've now reached a good neighborhood. Perform a much smaller
  // coordinate search over all six parameters.
  // ============================================================

  p = bestP.slice();

  let steps = [
    0.00025,  // beta0 = 2.5 bp
    0.00025,  // beta1
    0.00025,  // beta2
    0.00025,  // beta3
    0.10,     // tau1
    0.25      // tau2
  ];

  best = objective_(p);

  for (let iteration = 0; iteration < 100; iteration++) {

    let improved = false;
    for (let j = 0; j < 6; j++) {

      const original = p[j];

      // Try lower value.
      p[j] = original - steps[j];

      if (
        (j === 4 || j === 5) &&
        p[j] <= 0.05
      ) {

        p[j] = original;

      } else {

        let value = objective_(p);

        if (value < best) {

          best = value;
          improved = true;
          continue;
        }

        p[j] = original;
      }

      // Try higher value.
      p[j] = original + steps[j];

      let value = objective_(p);

      if (value < best) {

        best = value;
        improved = true;
        continue;
      }

      p[j] = original;
    }

    if (!improved) {

      let maxBetaStep = 0;
      let maxTauStep = 0;


      for (let j = 0;
        j < 6;
        j++) {

        steps[j] *= 0.5;

        if (j < 4) {
          maxBetaStep =
            Math.max(
              maxBetaStep,
              steps[j]
            );
        } else {
          maxTauStep =
            Math.max(
              maxTauStep,
              steps[j]
            );
        }
      }


      if (
        maxBetaStep < 1e-8 &&
        maxTauStep < 1e-5
      )
        break;
    }
  }

  Logger.log(
    `Svensson fit bonds=${prepared.length}`
  );

  Logger.log(
    `Svensson params=${p}`
  );

  Logger.log(
    `Svensson objective=${best}`
  );

  return {
    params: p,
    objective: best
  };
}