/**
 * Given a set of TIPS with current marketable clean prices, creates a
 * Svensson real zero-coupon curve fit and analyzes each security against
 * the fitted curve.
 *
 * Produces model clean prices, price residuals, market/model YTMs, and
 * yield-equivalent residuals in basis points.
 *
 * Input ranges may be Google Sheets column/row ranges. They are flattened
 * internally before processing.
 *
 * @param {Date} settle Settlement date
 * @param {Date[]} maturities Array/range of TIPS maturity dates
 * @param {number[]} coupons Array/range of matching annual coupons, decimal
 * @param {number[]} prices Array/range of matching quoted real clean prices
 *
 * @return {Array[]} 2D analysis table suitable for display in Sheets
 * @customfunction
 */
function mybondsZeroAnalyze(settle, maturities, coupons, prices, forward = null) {

  const settleDate = mydateNormalize_(settle);

  // Sheets normally supplies ranges as two-dimensional arrays such as
  // [[value1], [value2], ...]. Normalize them to simple one-dimensional arrays.
  maturities = maturities.flat();
  coupons = coupons.flat();
  prices = prices.flat();

  // Validate matching input dimensions.
  if (maturities.length !== coupons.length) {
    throw new Error(
      `maturities.length:${maturities.length} != coupons.length:${coupons.length}`
    );
  }

  if (maturities.length !== prices.length) {
    throw new Error(
      `maturities.length:${maturities.length} != prices.length:${prices.length}`
    );
  }

  if (maturities.length === 0) {
    throw new Error("No TIPS supplied");
  }

  // Build the bond objects expected by the Svensson fitter.
  const bonds = [];
  for (let i = 0; i < maturities.length; i++) {

    const maturity = mydateNormalize_(maturities[i]);
    const coupon = Number(coupons[i]);
    const cleanPrice = Number(prices[i]);

    if (!Number.isFinite(coupon)) {
      throw new Error(
        `Invalid coupon at input row ${i + 1}: ${coupons[i]}`
      );
    }

    if (!Number.isFinite(cleanPrice) || cleanPrice <= 0) {
      throw new Error(
        `Invalid clean price at input row ${i + 1}: ${prices[i]}`
      );
    }

    bonds.push({
      maturity: maturity,
      coupon: coupon,
      cleanPrice: cleanPrice
    });
  }

  // ------------------------------------------------------------
  // Fit the real Svensson zero-coupon curve.
  // ------------------------------------------------------------

  const fit = fitTipsSvensson_(settleDate, bonds);
  const params = fit.params;

  Logger.log(`params=${params}`);
  Logger.log(`objective=${fit.objective}`);

  // ------------------------------------------------------------
  // Sample fitted zero rates for diagnostic purposes.
  // These are continuously compounded real zero rates.
  // ------------------------------------------------------------
  /*
    const z5 = svenssonZero(5, params);
    const z10 = svenssonZero(10, params);
    const z20 = svenssonZero(20, params);
  
    Logger.log(
      `zero rates: 5Y=${z5}, 10Y=${z10}, 20Y=${z20}`
    );
  */

  // ------------------------------------------------------------
  // Create the 2D output table.
  // ------------------------------------------------------------
  const result = [[
    "Maturity",
    "Coupon",
    "Market Clean",
    "Model Clean",
    "Price Residual",
    "Market YTM",
    "Model YTM",
    "Residual (bp)"
  ]];

  // ------------------------------------------------------------
  // Analyze each TIPS against the fitted zero curve.
  // ------------------------------------------------------------

  for (const bond of bonds) {

    // Model dirty price from individually discounted real cash flows.
    const modelDirty =
      mytipsZeroModelPrice(
        settleDate,
        bond.maturity,
        bond.coupon,
        params
      );


    // Convert model dirty price to model clean price.
    const accrued =
      mybondAccruedInterest(
        settleDate,
        bond.maturity,
        bond.coupon
      );

    const modelClean = modelDirty - accrued;

    // Market minus model price.
    //
    // Negative:
    //   market price < model price
    //   bond is cheap to fitted zero curve
    //
    // Positive:
    //   market price > model price
    //   bond is rich to fitted zero curve
    //
    const priceResidual = bond.cleanPrice - modelClean;


    // Obtain conventional YTM for both the actual market price and
    // the synthetic price generated by the zero curve.
    const marketYtm =
      myYieldFromPrice(
        settleDate,
        bond.maturity,
        bond.coupon,
        bond.cleanPrice
      );

    const modelYtm =
      myYieldFromPrice(
        settleDate,
        bond.maturity,
        bond.coupon,
        modelClean
      );

    // Express the zero-curve price discrepancy as an equivalent
    // conventional YTM difference.
    //
    // Positive:
    //   market YTM > model YTM
    //   bond is cheap to fitted zero curve
    //
    // Negative:
    //   market YTM < model YTM
    //   bond is rich to fitted zero curve
    //
    const residualBp = (marketYtm - modelYtm) * 10000;

    // Add one row to the Sheets output table.
    result.push([
      bond.maturity,
      bond.coupon,
      bond.cleanPrice,
      mybondRoundPrice_(modelClean),
      mybondRoundPrice_(priceResidual),
      marketYtm,
      modelYtm,
      residualBp
    ]);
  }
  // ------------------------------------------------------------
  // Sample fitted zero rates for diagnostic purposes.
  // These are continuously compounded real zero rates.
  // ------------------------------------------------------------

  if (forward !== null && forward !== '') {
    result.push(['---']);
    const forwardDate = mydateNormalize_(forward);
    const fwdYrs = mydateDaysBetween_(settleDate, forwardDate) / mydateDaysInYearFrom_(settleDate);
    const zFwd = svenssonZero(fwdYrs, params);
    result.push([
      forwardDate,
      ,
      ,
      ,
      ,
      ,
      mybondRoundYield_(zFwd),
    ]);

    result.push(['---']);
    years = [1, 2, 5, 7, 10, 20, 30];
    const today = new Date;
    for (let i = 0; i < years.length; i++) {
      const date = new Date(today.getFullYear() + years[i], today.getMonth(), today.getDate());
      result.push([
        date,
        ,
        ,
        ,
        ,
        ,
        mybondRoundYield_(svenssonZero(years[i], params)),
      ]);
    }
    result.push(['--- NSS params']);
    result.push(params);
    result.push(['--- NSS Objective']);
    result.push(fit.objective);
  }
  // ------------------------------------------------------------
  // Return rectangular 2D array for Sheets.
  // ------------------------------------------------------------
  return result;
}

// find the difference between the bond and the model's dirty prices
function mytipsZeroResidual_(
  settle,
  bond,
  params
) {

  const accrued =
    mybondAccruedInterest(
      settle,
      bond.maturity,
      bond.coupon
    );

  const marketDirty =
    bond.cleanPrice + accrued;

  const modelDirty =
    mytipsZeroModelPrice(
      settle,
      bond.maturity,
      bond.coupon,
      params
    );

  return modelDirty - marketDirty;
}
/**
 * Svensson continuously compounded zero yield.
 * Input range p may be Google Sheets column/row range. It is flattened
 * internally before processing.
 *
 * @param {Date} settle Settlement date
 * @param {Date} maturity TIPS maturity date
 * @param {number} coupon decimal
 * @param {number[]} params [beta0,beta1,beta2,beta3,tau1,tau2]
 * @customfunction
 */
function mytipsZeroModelPrice(
  settle,
  maturity,
  coupon,
  params
) {

  const settleDate = mydateNormalize_(settle);

  const maturityDate = mydateNormalize_(maturity);
  const schedule = mybondCouponSchedule_(settleDate, maturityDate);

  if (schedule.length === 0)
    return null;

  let dirtyPV = 0;

  for (let i = 0;
    i < schedule.length;
    i++) {

    const paymentDate =
      schedule[i];

    const t =
      mydateDaysBetween_(
        settleDate,
        paymentDate
      ) / 365;

    const couponCF =
      100 * coupon / 2;

    const principal =
      (i === schedule.length - 1)
        ? 100
        : 0;

    const cf =
      couponCF + principal;

    dirtyPV +=
      cf * svenssonDF_(t, params);
  }

  return dirtyPV;
}

/**
 * Svensson discount factor
 * @param {number} t years (term)
 * @param {[]} p svensson parameter set
 * @returns number discount factor
*/
function svenssonDF_(t, p) {

  const z = svenssonZero(t, p);
  return Math.exp(-z * t);
}

/**
 * Svensson continuously compounded zero yield.
 * Input range p may be Google Sheets column/row range. It is flattened
 * internally before processing.
 *
 * @param {number} t years
 * @param {number[]} p [beta0,beta1,beta2,beta3,tau1,tau2]
 * @return {number} continuously compounded zero yield, decimal
 * @customfunction
 */
function svenssonZero(t, p) {

  const [b0, b1, b2, b3, tau1, tau2] = p.flat() ;

  if (t <= 0)
    return b0 + b1;

  const x1 = t / tau1;
  const x2 = t / tau2;

  const a1 =
    (1 - Math.exp(-x1)) / x1;

  const a2 =
    a1 - Math.exp(-x1);

  const a3 =
    (1 - Math.exp(-x2)) / x2
    - Math.exp(-x2);

  return b0 +
    b1 * a1 +
    b2 * a2 +
    b3 * a3;
}

/**
 * Optimized Svensson zero-curve fitter.
 *
 * Fits continuously compounded zero rates to observed bond dirty prices.
 *
 * Input bonds:
 * [
 *   {
 *     maturity: Date,
 *     coupon: decimal annual coupon,
 *     cleanPrice: quoted clean price
 *   },
 *   ...
 * ]
 *
 * Returns:
 * {
 *   params: [beta0, beta1, beta2, beta3, tau1, tau2],
 *   objective: weighted SSE
 * }
 *
 * Uses Node's deterministic tau-grid and Levenberg-Marquardt optimizer.
 * Compatible with svenssonZero(t, params).
 */
function fitTipsSvensson_(settle, bonds) {

  const settleDate = mydateNormalize_(settle);

  if (!Array.isArray(bonds) || bonds.length < 6) {
    throw new Error(
      `Svensson fit requires at least 6 bonds; found ${bonds?.length ?? 0}`
    );
  }

  // ============================================================
  // 1. PRECOMPUTE EVERYTHING THAT DOES NOT CHANGE DURING FITTING
  // ============================================================

  const prepared = [];

  for (const bond of bonds) {

    const maturityDate =
      mydateNormalize_(bond.maturity);

    const coupon =
      Number(bond.coupon);

    const cleanPrice =
      Number(bond.cleanPrice);

    if (!Number.isFinite(coupon) ||
      !Number.isFinite(cleanPrice) ||
      cleanPrice <= 0)
      continue;

    if (!mydateLessThan_(settleDate, maturityDate))
      continue;


    // Generate schedule ONCE.
    const schedule =
      mybondCouponSchedule_(
        settleDate,
        maturityDate
      );

    if (!schedule ||
      schedule.length === 0)
      continue;


    // Accrued interest ONCE.
    const accrued =
      mybondAccruedInterest(
        settleDate,
        maturityDate,
        coupon,
        schedule
      );

    const marketDirty =
      cleanPrice + accrued;


    // Precalculate times and cash flows.
    const times = new Array(schedule.length);
    const cashFlows = new Array(schedule.length);

    for (let i = 0; i < schedule.length; i++) {

      const t =
        mydateDaysBetween_(
          settleDate,
          schedule[i]
        ) / 365;

      times[i] = t;

      cashFlows[i] =
        100 *
        (
          coupon / 2 +
          (i === schedule.length - 1 ? 1 : 0)
        );
    }


    // duration used only for weighting.
    //
    // Using maturity here avoids calculating full modified duration
    // inside the fitting loop.
    // Calculate the observed market YTM once.
    // Used only to determine duration weighting.
    const marketYld =
      myYieldFromPrice(
        settleDate,
        maturityDate,
        coupon,
        cleanPrice
      );

    if (!Number.isFinite(marketYld))
      continue;

    // Calculate duration once, outside the optimizer.
    const duration =
      mybondCalcDuration(
        settleDate,
        maturityDate,
        coupon,
        marketYld
      );

    if (!Number.isFinite(duration) || duration <= 0)
      continue;

    // GSW objective uses inverse-duration weighting.
    const weight =
      1 / duration;


    prepared.push({
      marketDirty: marketDirty,
      times: times,
      cashFlows: cashFlows,
      weight: weight
    });
  }


  if (prepared.length < 6) {
    throw new Error(
      `Insufficient usable bonds for Svensson fit: ${prepared.length}`
    );
  }

  const fit = fitPreparedSvensson_(prepared);
  Logger.log(`Svensson fit bonds=${prepared.length}`);
  Logger.log(`Svensson params=${fit.params}`);
  Logger.log(`Svensson objective=${fit.objective}`);
  return fit;
}

/**
 * Deterministic tau grid with Levenberg-Marquardt beta fits and six-parameter polish.
 * Ported from lib/zero/svenssonFit.mjs; helpers stay local to avoid Apps Script globals.
 * @param {Array<{marketDirty:number,times:number[],cashFlows:number[],weight:number}>} prepared
 * @return {{params:number[], objective:number}}
 */
function fitPreparedSvensson_(prepared) {
  const TAU1_RANGE = [0.1, 15];
  const TAU2_RANGE = [0.5, 60];
  const MIN_TAU_RATIO = 1.05;
  const geometric = (lo, hi, n) => Array.from({ length: n }, (_, i) => lo * (hi / lo) ** (i / (n - 1)));
  const sumSquares = r => r.reduce((s, v) => s + v * v, 0);

  function inBounds(p) {
    const [, , , , tau1, tau2] = p;
    return tau1 >= TAU1_RANGE[0] && tau1 <= TAU1_RANGE[1]
      && tau2 >= TAU2_RANGE[0] && tau2 <= TAU2_RANGE[1]
      && tau2 >= tau1 * MIN_TAU_RATIO;
  }

  // Weighted residuals and analytic beta Jacobian.
  function evaluate(prepared, p, withJacobian) {
    const [b0, b1, b2, b3, tau1, tau2] = p;
    const n = prepared.length;
    const r = new Float64Array(n);
    const J = withJacobian ? Array.from({ length: n }, () => new Float64Array(4)) : null;
    for (let i = 0; i < n; i++) {
      const bond = prepared[i];
      const sw = Math.sqrt(bond.weight);
      let pv = 0;
      for (let k = 0; k < bond.times.length; k++) {
        const t = bond.times[k];
        const x1 = t / tau1;
        const e1 = Math.exp(-x1);
        const a1 = (1 - e1) / x1;
        const x2 = t / tau2;
        const e2 = Math.exp(-x2);
        const h = (1 - e2) / x2 - e2;
        const df = Math.exp(-(b0 + b1 * a1 + b2 * (a1 - e1) + b3 * h) * t);
        const cfdf = bond.cashFlows[k] * df;
        pv += cfdf;
        if (J) {
          const g = -cfdf * t * sw;
          J[i][0] += g;
          J[i][1] += g * a1;
          J[i][2] += g * (a1 - e1);
          J[i][3] += g * h;
        }
      }
      r[i] = sw * (pv - bond.marketDirty);
    }
    return { r, J };
  }

  function solve(A, b) {
    const m = b.length;
    const M = A.map((row, i) => [...row, b[i]]);
    for (let c = 0; c < m; c++) {
      let piv = c;
      for (let i = c + 1; i < m; i++) if (Math.abs(M[i][c]) > Math.abs(M[piv][c])) piv = i;
      if (Math.abs(M[piv][c]) < 1e-300) return null;
      [M[c], M[piv]] = [M[piv], M[c]];
      for (let i = c + 1; i < m; i++) {
        const f = M[i][c] / M[c][c];
        for (let j = c; j <= m; j++) M[i][j] -= f * M[c][j];
      }
    }
    const x = new Array(m);
    for (let i = m - 1; i >= 0; i--) {
      let s = M[i][m];
      for (let j = i + 1; j < m; j++) s -= M[i][j] * x[j];
      x[i] = s / M[i][i];
    }
    return x;
  }

  // Tau Jacobian columns use central differences.
  function levenbergMarquardt(prepared, start, free, maxIterations) {
    let p = start.slice();
    let sse = sumSquares(evaluate(prepared, p, false).r);
    let lambda = 1e-3;
    for (let iteration = 0; iteration < maxIterations; iteration++) {
      const { r, J } = evaluate(prepared, p, true);
      const cols = free.map(j => {
        if (j < 4) return J.map(row => row[j]);
        const h = 1e-5 * p[j];
        const up = p.slice(); up[j] += h;
        const dn = p.slice(); dn[j] -= h;
        const ru = evaluate(prepared, up, false).r;
        const rd = evaluate(prepared, dn, false).r;
        return Array.from(ru, (v, i) => (v - rd[i]) / (2 * h));
      });
      const m = free.length;
      const JtJ = Array.from({ length: m }, (_, a) => Array.from({ length: m }, (_, b) =>
        cols[a].reduce((s, v, i) => s + v * cols[b][i], 0)));
      const grad = cols.map(col => col.reduce((s, v, i) => s + v * r[i], 0));

      let accepted = false;
      for (let attempt = 0; attempt < 12; attempt++) {
        const damped = JtJ.map((row, a) => row.map((v, b) => (a === b ? v + lambda * Math.max(v, 1e-12) : v)));
        const step = solve(damped, grad.map(v => -v));
        if (!step || !step.every(Number.isFinite)) { lambda *= 10; continue; }
        const trial = p.slice();
        free.forEach((j, a) => { trial[j] += step[a]; });
        if (!inBounds(trial)) { lambda *= 10; continue; }
        const trialSse = sumSquares(evaluate(prepared, trial, false).r);
        if (Number.isFinite(trialSse) && trialSse < sse) {
          const converged = sse - trialSse <= 1e-13 * sse;
          p = trial;
          sse = trialSse;
          lambda = Math.max(lambda / 5, 1e-12);
          accepted = true;
          if (converged) return { p, sse };
          break;
        }
        lambda *= 10;
      }
      if (!accepted) break;
    }
    return { p, sse };
  }

  const candidates = [];
  for (const tau1 of geometric(0.3, 8, 12)) {
    for (const tau2 of geometric(2, 40, 12)) {
      if (tau2 < tau1 * 1.5) continue;
      const fit = levenbergMarquardt(prepared, [0.03, -0.01, 0, 0, tau1, tau2], [0, 1, 2, 3], 40);
      candidates.push(fit);
    }
  }
  candidates.sort((a, b) => a.sse - b.sse);
  let best = null;
  for (const candidate of candidates.slice(0, 8)) {
    const fit = levenbergMarquardt(prepared, candidate.p, [0, 1, 2, 3, 4, 5], 200);
    if (!best || fit.sse < best.sse) best = fit;
  }
  if (!best) throw new Error("Svensson fit failed to converge");
  return { params: best.p, objective: best.sse };
}